"""Write switch/steward-crew.template.yaml from the agents' briefs in agents/*.md.

The briefs are the source; the template is what you paste into Switch Console
(Templates, New template). Run this after editing a brief:

    python scripts/build_template.py
"""

from __future__ import annotations

import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "switch" / "steward-crew.template.yaml"

# Tools the agents may use: read, search, and the shell for the `steward`
# command. They get no editing tools and no web tools, and the shell refuses
# anything that could reach GitHub or the Keychain. The Ledger is the only
# thing that can change GitHub, and it is not an AI.
DENIED = [
    "Bash(gh:*)",
    "Bash(git push:*)",
    "Bash(git commit:*)",
    "Bash(curl:*)",
    "Bash(wget:*)",
    "Bash(security:*)",
    "Bash(rm:*)",
    "Bash(sqlite3:*)",
]

SKELETON = """\
# Steward Crew: an AI crew that looks after an open-source project's contributors.
# AI proposes, the Ledger acts, a maintainer decides.
#
# Generated by scripts/build_template.py from agents/*.md. Edit those, not this.
#
# Before you use it:
#   1. Post one message in Discord #help, so Switch makes it a room.
#   2. In Slack #maintainers type  /invite @Agent Switch  so Switch makes it a room.
#   3. Run scripts/setup.sh (it installs the `steward` command the agents use).
# Then Switch Console: Templates, New template, paste this, Use.
version: 1
params:
  help_room:
    type: room
    label: Community room (Discord #help)
    description: Where contributors ask questions. Stu answers here.
    default: [help, "#help"]
  maintainers_room:
    type: room
    label: Maintainers room (Slack #maintainers)
    description: Where Steward, the Reviewer and the Ledger work with maintainers.
    default: [maintainers, "#maintainers"]
  provider:
    type: provider
    default: [claude]
    input: advanced
  location:
    type: location
    default: local
    input: advanced
agents:
  - name: stu
    display_name: Stu (AI)
    description: The project's AI helper for contributors. Answers from the code, and asks a maintainer before anything happens on GitHub.
    directory: "{$agents_dir}/{agent}"
    addressing: anyone
    join: ["{help_room}"]
    advanced_config:
      tools: [Read, Grep, Glob, Bash]
      disallowedTools: @@DENIED@@
      maxTurns: 25
      effort: medium
    instructions: |
@@stu@@
  - name: steward
    display_name: Steward (AI)
    description: The maintainers' assistant. Writes the daily summary and files proposals; the Ledger acts only when a maintainer approves.
    directory: "{$agents_dir}/{agent}"
    addressing: anyone
    join: ["{maintainers_room}"]
    advanced_config:
      tools: [Read, Grep, Glob, Bash]
      disallowedTools: @@DENIED@@
      maxTurns: 40
      effort: high
    instructions: |
@@steward@@
  - name: reviewer
    display_name: Reviewer (AI)
    description: Reads pull requests against the issue and the code, and drafts a review for a maintainer to approve.
    directory: "{$agents_dir}/{agent}"
    addressing: anyone
    join: ["{maintainers_room}"]
    advanced_config:
      tools: [Read, Grep, Glob, Bash]
      disallowedTools: @@DENIED@@
      maxTurns: 30
      effort: high
    instructions: |
@@reviewer@@
form:
  advanced:
    label: Where the agents run
    open: false
"""


def build() -> str:
    text = SKELETON.replace("@@DENIED@@", "[" + ", ".join(f'"{d}"' for d in DENIED) + "]")
    for name in ("stu", "steward", "reviewer"):
        brief = (ROOT / "agents" / f"{name}.md").read_text(encoding="utf-8").strip()
        text = text.replace(f"@@{name}@@", textwrap.indent(brief, " " * 6, lambda line: True).rstrip())
    # Blank lines inside a block scalar must not carry trailing spaces.
    return "\n".join(line.rstrip() for line in text.splitlines()) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("switch/steward-crew.template.yaml is out of date: run python scripts/build_template.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
